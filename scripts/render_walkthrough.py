from datetime import datetime, timezone
import json
import math
from pathlib import Path
import re
import shutil
import subprocess
import tempfile
import unicodedata
from urllib.parse import urlsplit
import wave

from render_public_media import parse_captions, stamp
from verify_capture_evidence import APPS, SHA256, _Validator, _caption_cues, _hash, _image_dimensions, _normalized


WIDTH, HEIGHT, FPS = 1920, 1080, 30
HEADER, FOOTER = 48, 120
EPSILON = 0.001  # Inputs are explicit milliseconds; do not conceal timeline gaps.


class AssemblyError(ValueError):
    """An actionable input, media, or rendering failure."""


def need(condition, field, message):
    if not condition:
        raise AssemblyError(f"{field}: {message}")


def mapping(value, field):
    need(isinstance(value, dict), field, "must be an object")
    return value


def items(value, field, empty=False):
    need(isinstance(value, list) and (empty or bool(value)), field, "must be a nonempty list" if not empty else "must be a list")
    return value


def text(value, field):
    need(isinstance(value, str) and bool(value.strip()), field, "must be nonempty text")
    return value


def number(value):
    return isinstance(value, (int, float)) and not isinstance(value, bool) and math.isfinite(value)


def words(value):
    value = unicodedata.normalize("NFKC", value).replace("’", "'").casefold()
    return re.findall(r"[^\W_]+(?:'[^\W_]+)*", value, re.UNICODE)


def timestamp(value, field):
    try:
        parsed = datetime.fromisoformat(value.replace("Z", "+00:00"))
        need(parsed.tzinfo is not None, field, "include a timezone")
        need(parsed <= datetime.now(timezone.utc), field, "review/capture cannot be in the future")
        return parsed
    except (AttributeError, TypeError, ValueError) as exc:
        raise AssemblyError(f"{field}: record an actual ISO-8601 timestamp with timezone") from exc


def read_json(path):
    try:
        return json.loads(Path(path).read_text(encoding="utf-8"))
    except (OSError, UnicodeError, json.JSONDecodeError) as exc:
        raise AssemblyError(f"{path}: cannot read JSON: {exc}") from exc


def asset(reference, root, field):
    reference = mapping(reference, field)
    name = text(reference.get("file"), field + ".file")
    path = (root / name).resolve()
    need(not Path(name).is_absolute() and root in path.parents, field + ".file", "use a path inside asset_root")
    need(path.is_file() and path.stat().st_size > 0, field + ".file", f"missing or empty asset {name!r}")
    digest = reference.get("sha256")
    need(isinstance(digest, str) and SHA256.fullmatch(digest), field + ".sha256", "record the asset's SHA-256")
    need(_hash(path) == digest.lower(), field + ".sha256", f"hash mismatch for {name!r}; review the current asset")
    return path


def review(value, digest, field):
    value = mapping(value, field)
    text(value.get("reviewer"), field + ".reviewer")
    timestamp(value.get("reviewed_at"), field + ".reviewed_at")
    need(value.get("sha256") == digest, field + ".sha256", "review must be tied to this exact asset hash")
    return value


def span(value, field, bounds):
    value = mapping(value, field)
    start, end = value.get("start"), value.get("end")
    need(number(start) and number(end) and 0 <= start < end, field, "require finite seconds with 0 <= start < end")
    need(start >= bounds[0] - EPSILON and end <= bounds[1] + EPSILON, field, "interval is outside its scene/video")
    return start, end


def coverage(intervals, bounds, field):
    cursor = bounds[0]
    for start, end in intervals:
        need(abs(start - cursor) <= EPSILON, field, f"gap/overlap at {cursor:g}s; next explicit interval starts at {start:g}s")
        cursor = end
    need(abs(cursor - bounds[1]) <= EPSILON, field, f"coverage ends at {cursor:g}s; expected {bounds[1]:g}s")


def layout(width, height):
    """Fit the complete screenshot in the main canvas, never crop or cover it."""
    need(isinstance(width, int) and isinstance(height, int) and not isinstance(width, bool) and not isinstance(height, bool), "screenshot.dimensions", "must be integer pixels")
    need(width >= 960 and height >= 540, "screenshot.dimensions", "recapture a landscape viewport of at least 960x540 for readable controls")
    scale = min(WIDTH / width, (HEIGHT - HEADER - FOOTER) / height)
    fitted_width, fitted_height = round(width * scale), round(height * scale)
    need(scale >= 0.75 and fitted_width >= 1100 and fitted_height >= 650, "screenshot.layout", "full screenshot would be too small; recapture a landscape viewport with larger UI text instead of an inset/full-page image")
    return {"x": (WIDTH - fitted_width) // 2, "y": HEADER + (HEIGHT - HEADER - FOOTER - fitted_height) // 2,
            "width": fitted_width, "height": fitted_height, "scale": scale, "cropped": False}


def load_cues(path):
    try:
        raw = path.read_text(encoding="utf-8-sig")
        blocks = re.split(r"\n\s*\n", raw.replace("\r\n", "\n").strip())
        for index, block in enumerate(blocks, 1):
            lines = block.splitlines()
            need(len(lines) >= 3 and lines[0].strip() == str(index) and "-->" in lines[1], f"captions[{index}]", "require sequential SRT cue numbers, timing and speech text; do not silently discard blocks")
        strict = _caption_cues(raw)
        cues = parse_captions(raw)
        need(bool(cues) and len(cues) == len(strict), "captions", "provide a complete speech-timed SRT export")
        for index, (cue, checked) in enumerate(zip(cues, strict), 1):
            need(abs(cue["start"] - checked[0]) < 1e-9 and abs(cue["end"] - checked[1]) < 1e-9 and _normalized(cue["text"]) == checked[2], f"captions[{index}]", "invalid caption text/timing")
            # Both parsers read the same explicit SRT milliseconds. Different
            # addition order can differ by a binary float bit after one minute.
            # Keep the strict parser's times; never move or estimate a cue.
            cue["start"], cue["end"] = checked[:2]
            need(cue["start"] >= 0 and cue["end"] > cue["start"], f"captions[{index}]", "invalid cue interval")
            need(cue["end"] - cue["start"] >= 2 / FPS, f"captions[{index}]", "cue is shorter than two video frames; correct the actual aligned export instead of dropping it")
            need(not re.search(r"<[^>]*>|\{\\", cue["text"]), f"captions[{index}]", "use plain speech captions without HTML/ASS styling")
            if index > 1:
                need(cue["start"] >= cues[index - 2]["end"] - EPSILON, f"captions[{index}]", "overlapping/out-of-order speech cues; use the actual aligned export")
        return cues
    except (OSError, UnicodeError, ValueError) as exc:
        raise AssemblyError(f"captions: cannot read valid speech-timed SRT: {exc}") from exc


def validate_inputs(lesson_path, plan_path, asset_root):
    """Validate the explicit recipe without creating media or inventing timings."""
    root = Path(asset_root).resolve()
    lesson, plan = read_json(lesson_path), read_json(plan_path)
    mapping(lesson, "lesson"); mapping(plan, "plan")
    need(plan.get("schema_version") == 1 and not isinstance(plan.get("schema_version"), bool), "plan.schema_version", "must be 1")
    ident = text(lesson.get("id"), "lesson.id")
    text(lesson.get("title"), "lesson.title")
    need(re.fullmatch(r"[a-zA-Z0-9][a-zA-Z0-9_-]*", ident), "lesson.id", "use a safe lesson identifier")
    need(plan.get("lesson_id") == ident, "plan.lesson_id", "must match lesson.id")
    need(isinstance(lesson.get("app"), str) and lesson.get("app") in APPS, "lesson.app", "must be Core, Dispatch, Responder, Unit or IC")
    application_validator = _Validator(root)
    supporting = application_validator.supporting_applications(plan.get("supporting_applications", []), lesson["app"], "plan.supporting_applications")
    need(not application_validator.issues, "plan.supporting_applications", "; ".join(application_validator.issues))
    duration = plan.get("duration_seconds")
    instruction_mapping = plan.get("instruction_mapping")
    need(instruction_mapping in (None, "reviewed_scene_coverage"), "plan.instruction_mapping", "use reviewed_scene_coverage only with an explicit hash-bound instruction review")
    reviewed_mode = instruction_mapping == "reviewed_scene_coverage"
    if "display_context" in plan:
        context = text(plan["display_context"], "plan.display_context")
        need(len(context) <= 80 and '\n' not in context and '\r' not in context, "plan.display_context", "use a short accurate context label outside the untouched application image")
    need(number(duration) and duration > 0, "plan.duration_seconds", "record the complete decoded narration duration; no estimated cue timing")
    narration = mapping(plan.get("narration"), "plan.narration")
    audio = asset(narration, root, "plan.narration")
    need(narration.get("kind") == "approved_natural_narration", "plan.narration.kind", "require approved local natural narration; no generated fallback")
    approval = review(narration.get("approval"), narration["sha256"], "plan.narration.approval")
    need(approval.get("complete_natural_narration") is True, "plan.narration.approval", "review the full audio for natural speech and completeness")
    caption_ref = mapping(plan.get("captions"), "plan.captions")
    srt = asset(caption_ref, root, "plan.captions")
    need(srt.suffix.lower() == ".srt" and caption_ref.get("kind") == "speech_timed_srt", "plan.captions", "require an existing speech-timed .srt export")
    alignment = review(caption_ref.get("approval"), caption_ref["sha256"], "plan.captions.approval")
    need(alignment.get("audio_sha256") == narration["sha256"] and alignment.get("speech_timing_reviewed") is True, "plan.captions.approval", "review actual speech alignment for this exact audio; do not manufacture timings")
    cues = load_cues(srt)
    need(cues[-1]["end"] <= duration + EPSILON, "captions", "last spoken cue extends beyond the planned video")
    screenshots, sources = {}, [Path(lesson_path).resolve(), Path(plan_path).resolve(), audio, srt]
    for index, reference in enumerate(items(plan.get("capture_manifests"), "plan.capture_manifests")):
        mf = f"plan.capture_manifests[{index}]"
        path = asset(reference, root, mf); sources.append(path)
        document = mapping(read_json(path), mf)
        rows = document.get("captures", document.get("screenshots"))
        for row in items(rows, mf + ".captures"):
            row = mapping(row, mf + ".capture")
            sid = text(row.get("id"), mf + ".capture.id")
            need(sid not in screenshots, mf, f"duplicate screenshot id {sid!r}; use unambiguous capture IDs")
            screenshots[sid] = row
    reviews = mapping(plan.get("screenshot_reviews"), "plan.screenshot_reviews")
    selected = {}

    def select_screen(sid, field):
        need(sid in screenshots, field, f"unknown screenshot {sid!r}")
        if sid in selected:
            return selected[sid]
        row = screenshots[sid]
        application_validator = _Validator(root)
        application_validator.application(row, field, supporting)
        need(not application_validator.issues, field, "; ".join(application_validator.issues))
        need(row.get("app") == lesson["app"] or row.get("app") in supporting, field, "screenshot app must match this lesson's source application or its explicitly declared local receiver")
        need(row.get("kind") == "application_screenshot", field, "illustrated substitutes are forbidden; require actual application_screenshot")
        need(row.get("eligible_for_lesson") is not False and not str(row.get("state", "")).startswith(("excluded", "blocked", "loading", "error", "failed")), field, "capture is excluded/blocked; recapture the actual successful or deliberately taught application state")
        need(not row.get("missing_required_labels"), field, "capture manifest reports missing required controls; correct/review the viewport evidence first")
        image = asset(row, root, field)
        try:
            dimensions = _image_dimensions(image)
        except (OSError, ValueError) as exc:
            raise AssemblyError(f"{field}: cannot read PNG/JPEG screenshot: {exc}") from exc
        need(dimensions == (row.get("width"), row.get("height")), field, "image header dimensions do not match capture metadata")
        native_report = None
        provenance = mapping(row.get("provenance"), field + ".provenance")
        if provenance.get("method") == "ios_simulator_screenshot":
            try:
                from native_capture_public import validate_native_source
                native_report = validate_native_source(row, root, lesson["app"])
            except (ValueError, OSError, TypeError, KeyError) as exc:
                raise AssemblyError(f"{field}: {exc}") from exc
            fitted = native_report["layout"]
            sources.extend(native_report["dependencies"])
        else:
            fitted = layout(*dimensions)
            need(provenance.get("method") == "browser_screenshot" and "native_review_package" not in row, field, "require actual browser capture provenance; native evidence cannot be relabeled")
            try:
                url = urlsplit(text(provenance.get("url"), field + ".url"))
            except ValueError as exc:
                raise AssemblyError(f"{field}.url: malformed application URL") from exc
            need(url.scheme in ("http", "https") and url.hostname and not url.username and not url.password, field + ".url", "require the actual application http(s) URL without credentials")
            need(not any(key in url.query.lower() for key in ("access_token=", "token=", "api_key=", "password=")), field + ".url", "redact credential-bearing URL query values before recording provenance")
        captured_at = timestamp(provenance.get("captured_at"), field + ".captured_at")
        control_validator = _Validator(root)
        observed_names = control_validator.observations(row, field)
        need(not control_validator.issues, field, "; ".join(control_validator.issues))
        observed = items(row.get("visible_labels"), field + ".visible_labels", empty=bool(row.get("visible_controls")))
        need(all(isinstance(label, str) and label.strip() for label in observed), field + ".visible_labels", "record actual viewport labels")
        checked = review(reviews.get(sid), row["sha256"], f"plan.screenshot_reviews.{sid}")
        need(timestamp(checked["reviewed_at"], field + ".reviewed_at") >= captured_at, field, "review predates this screenshot")
        for flag in ("application_visible", "labels_legible", "no_errors"):
            need(checked.get(flag) is True, f"plan.screenshot_reviews.{sid}.{flag}", "requires genuine visual review of this screenshot")
        selected[sid] = {"metadata": row, "path": image, "layout": fitted, "observed_names": observed_names}
        if native_report is not None:
            selected[sid]["native_binding"] = native_report["native_binding"]
        sources.append(image)
        if "dom_file" in row or "dom_sha256" in row:
            sources.append(asset({"file": row.get("dom_file"), "sha256": row.get("dom_sha256")}, root, field + ".dom"))
        return selected[sid]

    lesson_scenes = items(lesson.get("scenes"), "lesson.scenes")
    planned = items(plan.get("scenes"), "plan.scenes")
    need(len(planned) == len(lesson_scenes), "plan.scenes", "map every authored scene exactly once; do not leave narration unrendered")
    seen_cues, scene_ids, intervals, built = set(), set(), [], []
    for index, (authored, scene) in enumerate(zip(lesson_scenes, planned)):
        field = f"plan.scenes[{index}]"
        mapping(authored, "lesson.scene"); mapping(scene, field)
        app_validator = _Validator(root)
        instruction_app = app_validator.instruction_application(scene, lesson["app"], supporting, field)
        need(not app_validator.issues, field, "; ".join(app_validator.issues))
        sid = text(scene.get("id"), field + ".id")
        need(sid == authored.get("id") and sid not in scene_ids, field + ".id", "map unique lesson scene IDs in authored order")
        scene_ids.add(sid)
        interval = span(scene, field, (0, duration)); intervals.append(interval)
        screens, screen_intervals = [], []
        for si, screen in enumerate(items(scene.get("screens"), field + ".screens")):
            sf = f"{field}.screens[{si}]"; mapping(screen, sf)
            ssid = text(screen.get("screenshot_id"), sf + ".screenshot_id")
            select_screen(ssid, sf)
            times = span(screen, sf, interval); screen_intervals.append(times)
            need(times[1] - times[0] >= 2 / FPS, sf, "screen interval is shorter than two video frames; use a legible explicit capture plan")
            screens.append({"screenshot_id": ssid, "start": times[0], "end": times[1]})
        coverage(screen_intervals, interval, field + ".screens")
        mapped, required_found = [], set()
        for ci, entry in enumerate(items(scene.get("captions"), field + ".captions")):
            cf = f"{field}.captions[{ci}]"; mapping(entry, cf)
            cue_number = entry.get("cue")
            need(isinstance(cue_number, int) and not isinstance(cue_number, bool) and 1 <= cue_number <= len(cues), cf + ".cue", "reference an existing one-based speech cue")
            need(cue_number not in seen_cues, cf, "each speech cue must map exactly once")
            seen_cues.add(cue_number)
            cue = cues[cue_number - 1]
            need(cue["start"] >= interval[0] - EPSILON and cue["end"] <= interval[1] + EPSILON, cf, "speech cue extends outside this scene; do not move its timing to fit")
            screenshot_id = text(entry.get("screenshot_id"), cf + ".screenshot_id")
            need(any(s["screenshot_id"] == screenshot_id and s["start"] <= cue["start"] + EPSILON and s["end"] >= cue["end"] - EPSILON for s in screens), cf, "the mapped real screen must cover the entire speech cue; split cues using actual speech alignment at screen cuts")
            instructional = entry.get("instructional", True)
            need(isinstance(instructional, bool), cf + ".instructional", "must be true or false")
            labels = items(entry.get("required_labels"), cf + ".required_labels", empty=not instructional)
            need(all(isinstance(label, str) and label.strip() for label in labels), cf + ".required_labels", "use exact visible UI text or reviewed accessible control names")
            observed = selected[screenshot_id]["observed_names"]
            speech_validator = _Validator(root)
            speech_validator.spoken_references(dict(cue, spoken_references=entry.get("spoken_references", {})), {_normalized(label) for label in labels}, cf, reviewed_mode)
            need(not speech_validator.issues, cf, "speech cue does not name mapped control or lacks its reviewed reference: " + "; ".join(speech_validator.issues))
            for label in labels:
                normalized = _normalized(label)
                need(normalized in observed, cf + ".required_labels", f"visible control {label!r} is missing from screenshot {screenshot_id!r}")
                if selected[screenshot_id]["metadata"]["app"] == instruction_app:
                    required_found.add(normalized)
            mapped_caption = {**cue, "cue": cue_number, "screenshot_id": screenshot_id, "required_labels": labels, "instructional": instructional}
            if entry.get("spoken_references") is not None:
                mapped_caption["spoken_references"] = entry["spoken_references"]
            mapped.append(mapped_caption)
        need([c["cue"] for c in mapped] == sorted(c["cue"] for c in mapped), field + ".captions", "keep actual speech cues in order")
        need(words(" ".join(c["text"] for c in mapped)) == words(text(authored.get("narration"), "lesson.scene.narration")), field + ".captions", "complete spoken transcript must match authored narration; missing/extra/changed words need an approved script/audio correction, never estimated timing")
        expected = {_normalized(text(label, "lesson.scene.required_labels")) for label in items(authored.get("required_labels"), "lesson.scene.required_labels")}
        if not reviewed_mode:
            need(expected <= required_found, field + ".captions", f"unmatched authored UI controls: {sorted(expected - required_found)}")
        for screen in screens:
            need(any(c["screenshot_id"] == screen["screenshot_id"] and c["start"] >= screen["start"] - EPSILON and c["end"] <= screen["end"] + EPSILON for c in mapped), field, "every displayed screen interval needs a speech-cue mapping for rendered frame review")
        built_scene = {"id": sid, "title": text(authored.get("title"), "lesson.scene.title"), "kind": "operational", "start": interval[0], "end": interval[1], "screens": screens, "captions": mapped}
        if "instruction_app" in scene:
            built_scene["instruction_app"] = instruction_app
        if reviewed_mode:
            need(any(c["required_labels"] for c in mapped), field + ".captions", "an operational scene still needs a speech-to-visible-control instruction")
            built_scene.update(visual_required_labels=authored["required_labels"], instruction_review=scene.get("instruction_review"))
            instruction_validator = _Validator(root)
            instruction_validator.instruction_review(built_scene, {key: value["metadata"] for key, value in selected.items()}, {key: value["observed_names"] for key, value in selected.items()}, field, instruction_app)
            need(not instruction_validator.issues, field, "; ".join(instruction_validator.issues))
        built.append(built_scene)
    coverage(intervals, (0, duration), "plan.scenes")
    need(seen_cues == set(range(1, len(cues) + 1)), "plan.scenes", "every actual spoken SRT cue needs a scene/screen mapping; no narration may be dropped")
    return {"root": root, "lesson": lesson, "plan": plan, "duration": duration, "audio": audio, "srt": srt,
            "cues": cues, "scenes": built, "screenshots": selected, "source_hashes": {str(p): _hash(p) for p in dict.fromkeys(sources)}}


def run(command, field):
    try:
        result = subprocess.run(command, capture_output=True, text=True, check=False)
    except OSError as exc:
        raise AssemblyError(f"{field}: cannot run FFmpeg: {exc}") from exc
    need(result.returncode == 0 and not result.stderr.strip(), field, "FFmpeg failed: " + result.stderr[-1800:])
    return result


def audio_duration(ffmpeg, source, destination):
    """Decode every audio sample; render this exact untrimmed PCM as AAC."""
    run([str(ffmpeg), "-nostdin", "-v", "error", "-y", "-i", str(source), "-map", "0:a:0", "-vn", "-ac", "1", "-ar", "48000", "-c:a", "pcm_s16le", str(destination)], "narration.decode")
    with wave.open(str(destination), "rb") as stream:
        return stream.getnframes() / stream.getframerate()


def check_audio_duration(duration, planned):
    need(duration > 0, "narration.duration", "decoded narration is empty")
    need(planned >= duration - 0.000001, "plan.duration_seconds", f"would truncate narration ({duration:.6f}s); extend the explicit final screen interval")
    need(planned - duration <= 1 / FPS + EPSILON, "plan.duration_seconds", f"must match decoded narration ({duration:.6f}s) within one frame; do not insert an estimated tail")


def probe_output(ffmpeg, movie, expected_duration):
    """Inspect the actual muxed streams; FFmpeg -i intentionally has no output."""
    result = subprocess.run([str(ffmpeg), "-nostdin", "-hide_banner", "-i", str(movie)], capture_output=True, text=True)
    info = result.stderr
    duration = re.search(r"Duration: (\d+):(\d+):(\d+(?:\.\d+)?)", info)
    need(bool(duration), "render.probe", "cannot read actual output duration")
    seconds = int(duration[1]) * 3600 + int(duration[2]) * 60 + float(duration[3])
    need(abs(seconds - expected_duration) <= 1 / FPS + 0.01, "render.probe", "muxed duration differs from the complete explicit timeline")
    need(re.search(r"Video: h264[^\n]*\b1920x1080\b", info), "render.probe", "output must actually contain 1920x1080 H264")
    need(re.search(r"Audio: aac\b", info), "render.probe", "output must actually contain AAC narration")
    return {"duration_seconds": seconds, "video_codec": "h264", "audio_codec": "aac", "width": WIDTH, "height": HEIGHT}


def caption_text(cues, at):
    return next((cue["text"] for cue in cues if cue["start"] <= at < cue["end"]), "")


def timeline(recipe):
    """Cut only at supplied scene/screen/caption boundaries, without retiming speech."""
    result = []
    for scene in recipe["scenes"]:
        for screen in scene["screens"]:
            cuts = sorted({screen["start"], screen["end"], *(t for cue in scene["captions"] for t in (cue["start"], cue["end"]) if screen["start"] < t < screen["end"])})
            for start, end in zip(cuts, cuts[1:]):
                result.append({"scene_id": scene["id"], "title": scene["title"], "screenshot_id": screen["screenshot_id"], "start": start, "end": end, "caption": caption_text(scene["captions"], (start + end) / 2)})
    return result


def caption_wrap(draw, value, font, max_width):
    lines = []
    for word in value.split():
        need(draw.textbbox((0, 0), word, font=font)[2] <= max_width, "captions.layout", "caption contains an overlong word; revise the aligned caption export")
        if not lines or draw.textbbox((0, 0), lines[-1] + " " + word, font=font)[2] > max_width:
            lines.append(word)
        else:
            lines[-1] += " " + word
    need(len(lines) <= 3, "captions.layout", "cue needs more than three readable lines; split it at genuine speech timings, never shrink the application")
    return lines


def make_frame(recipe, entry, destination, font_path):
    from PIL import Image, ImageDraw, ImageFont
    selected = recipe["screenshots"][entry["screenshot_id"]]
    image = Image.new("RGB", (WIDTH, HEIGHT), "#111827")
    with Image.open(selected["path"]) as original:
        original.load()
        box = selected["layout"]
        image.paste(original.convert("RGB").resize((box["width"], box["height"]), Image.Resampling.LANCZOS), (box["x"], box["y"]))
    draw = ImageDraw.Draw(image)
    title_font, subtitle_font = ImageFont.truetype(str(font_path), 27), ImageFont.truetype(str(font_path), 30)
    context = recipe["plan"].get("display_context")
    title = (context + " · " if context else "") + entry["title"]
    need(draw.textbbox((0, 0), title, font=title_font)[2] <= WIDTH - 64, "scene.title", "chapter title is too long for the small header; shorten the approved title")
    draw.text((32, 9), title, font=title_font, fill="white")
    lines = caption_wrap(draw, entry["caption"], subtitle_font, WIDTH - 120)
    for index, line in enumerate(lines):
        draw.text(((WIDTH - draw.textbbox((0, 0), line, font=subtitle_font)[2]) / 2, HEIGHT - FOOTER + 7 + index * 34), line, font=subtitle_font, fill="white")
    image.save(destination)


def ffmetadata(chapters, title):
    def escaped(value):
        return str(value).replace("\\", "\\\\").replace("\n", " ").replace("\r", " ").replace("=", "\\=").replace(";", "\\;").replace("#", "\\#")
    data = ";FFMETADATA1\ntitle=" + escaped(title) + "\n"
    for chapter in chapters:
        data += f'[CHAPTER]\nTIMEBASE=1/1000\nSTART={round(chapter["start"] * 1000)}\nEND={round(chapter["end"] * 1000)}\ntitle={escaped(chapter["title"])}\n'
    return data


def find_font(explicit=None):
    candidates = [Path(explicit)] if explicit else [Path("/System/Library/Fonts/Supplemental/Arial.ttf"), Path("/usr/share/fonts/truetype/dejavu/DejaVuSans.ttf")]
    for candidate in candidates:
        if candidate.is_file():
            return candidate.resolve()
    raise AssemblyError("font: pass --font with an existing readable TrueType font")


def render(lesson_path, plan_path, asset_root, output_dir, ffmpeg="ffmpeg", font=None, check_only=False):
    recipe = validate_inputs(lesson_path, plan_path, asset_root)
    output, root = Path(output_dir).resolve(), recipe["root"]
    need(root in output.parents, "output_dir", "use a new staging directory inside asset_root")
    need(not output.exists(), "output_dir", "already exists; choose a new staging directory so previous work is preserved")
    font_path = find_font(font)
    # Temporary work is outside the canonical source tree. Commit no partial outputs.
    with tempfile.TemporaryDirectory(prefix="academy-walkthrough-") as directory:
        working = Path(directory); wav = working / "narration.wav"
        measured = audio_duration(ffmpeg, recipe["audio"], wav)
        check_audio_duration(measured, recipe["duration"])
        if check_only:
            return {"passed": True, "lesson_id": recipe["lesson"]["id"], "decoded_audio_seconds": measured,
                    "publishable": False, "status": "inputs_checked_only; no video or playback proof produced"}
        try:
            import PIL  # noqa: F401 -- actionable dependency error before rendering.
        except ImportError as exc:
            raise AssemblyError("render: Pillow is required; use the supplied runtime, without installing into the app repositories") from exc
        staging = working / "output"; staging.mkdir()
        listing, entries = [], timeline(recipe)
        for index, entry in enumerate(entries):
            frame = working / f"screen-{index:05}.png"
            make_frame(recipe, entry, frame, font_path)
            listing.extend(["file '" + frame.as_posix().replace("'", "'\\''") + "'", "option framerate 1000", f'duration {entry["end"] - entry["start"]:.9f}'])
        listing.extend([listing[-3], "option framerate 1000"])
        concat = working / "screens.txt"; concat.write_text("\n".join(listing) + "\n")
        ident = recipe["lesson"]["id"]
        srt, vtt = staging / (ident + ".srt"), staging / (ident + ".vtt")
        # SRT source bytes are retained exactly. VTT changes only the container syntax.
        shutil.copyfile(recipe["srt"], srt)
        vtt.write_text("WEBVTT\n\n" + "".join(f'{stamp(c["start"])} --> {stamp(c["end"])}\n{c["text"]}\n\n' for c in recipe["cues"]), encoding="utf-8")
        chapters = [{k: scene[k] for k in ("id", "title", "start", "end")} for scene in recipe["scenes"]]
        chapter_file = staging / (ident + ".chapters.json"); chapter_file.write_text(json.dumps(chapters, indent=2) + "\n")
        metadata = working / "chapters.ffmetadata"; metadata.write_text(ffmetadata(chapters, recipe["lesson"]["title"]), encoding="utf-8")
        movie = staging / (ident + ".mp4")
        # A millisecond movie clock can round an edit-list endpoint down and
        # discard the last PCM samples. Match the clock to the decoded audio.
        run([str(ffmpeg), "-nostdin", "-hide_banner", "-v", "error", "-y", "-f", "concat", "-safe", "0", "-i", str(concat), "-i", str(wav), "-i", str(srt), "-f", "ffmetadata", "-i", str(metadata), "-map", "0:v:0", "-map", "1:a:0", "-map", "2:0", "-map_metadata", "3", "-map_chapters", "3", "-t", str(recipe["duration"]), "-vf", f"fps={FPS}", "-r", str(FPS), "-c:v", "libx264", "-preset", "veryfast", "-tune", "stillimage", "-crf", "18", "-threads", "2", "-pix_fmt", "yuv420p", "-c:a", "aac", "-b:a", "192k", "-c:s", "mov_text", "-metadata:s:s:0", "language=eng", "-movie_timescale", "48000", "-movflags", "+faststart", str(movie)], "render")
        decoded = run([str(ffmpeg), "-nostdin", "-v", "error", "-nostats", "-i", str(movie), "-map", "0:v:0", "-map", "0:a:0", "-progress", "pipe:1", "-f", "null", "-"], "render.full_decode")
        counts = re.findall(r"^frame=(\d+)\s*$", decoded.stdout, re.MULTILINE)
        frame_count = int(counts[-1]) if counts else 0
        need(abs(frame_count - recipe["duration"] * FPS) <= 1.01, "render.full_decode", "decoded video frames do not cover the full narration timeline")
        media_info = probe_output(ffmpeg, movie, recipe["duration"])
        decoded_output_audio = audio_duration(ffmpeg, movie, working / "output-audio.wav")
        need(decoded_output_audio >= measured - 1 / 48000 and decoded_output_audio <= measured + 0.1, "render.audio", "output narration is truncated or unexpectedly padded; preserve every source speech sample")
        digest = _hash(movie)
        relative = lambda path: (output / path.relative_to(staging)).relative_to(root).as_posix()
        file_ref = lambda path: {"file": relative(path), "sha256": _hash(path)}
        poster = staging / (ident + ".jpg")
        run([str(ffmpeg), "-nostdin", "-v", "error", "-y", "-i", str(movie), "-frames:v", "1", "-update", "1", str(poster)], "poster.extract")
        proof_dir = staging / "frames"; proof_dir.mkdir()
        segments = []
        for scene in recipe["scenes"]:
            for screen in scene["screens"]:
                cue = next(c for c in scene["captions"] if c["screenshot_id"] == screen["screenshot_id"] and c["start"] >= screen["start"] - EPSILON and c["end"] <= screen["end"] + EPSILON)
                at = (cue["start"] + cue["end"]) / 2
                frame = proof_dir / f"frame-{len(segments)+1:04}.png"
                run([str(ffmpeg), "-nostdin", "-v", "error", "-y", "-i", str(movie), "-ss", f"{at:.6f}", "-frames:v", "1", "-update", "1", str(frame)], "frame.extract")
                need(_image_dimensions(frame) == (WIDTH, HEIGHT), "frame.extract", "decoded frame is not 1920x1080")
                segments.append({"scene_id": scene["id"], **screen, "frame": {**file_ref(frame), "width": WIDTH, "height": HEIGHT, "time": at, "video_sha256": digest,
                    "review_status": "pending_actual_frame_review", "application_visible": None, "visible_labels": [], "reviewed_control_names": [], "caption_text": cue["text"]}})
                native_binding = recipe["screenshots"][screen["screenshot_id"]].get("native_binding")
                if native_binding is not None:
                    segments[-1]["frame"].update(native_binding=native_binding, native_frame_review=None)
        for path, original_hash in recipe["source_hashes"].items():
            need(_hash(Path(path)) == original_hash, "source_hashes", "a source changed during rendering; discard and re-review current inputs")
        assembled = datetime.now(timezone.utc).isoformat()
        evidence = {"schema_version": 1, "lesson_id": ident,
                    "video": {**file_ref(movie), "duration_seconds": recipe["duration"], "width": WIDTH, "height": HEIGHT, "assembled_at": assembled, "captions": file_ref(vtt)},
                    "screenshots": [s["metadata"] for s in recipe["screenshots"].values()],
                    "scenes": recipe["scenes"], "rendered_segments": segments, "browser_playback": []}
        if recipe["plan"].get("supporting_applications"):
            evidence.update(primary_app=recipe["lesson"]["app"], supporting_applications=recipe["plan"]["supporting_applications"])
        if any("native_binding" in shot for shot in recipe["screenshots"].values()):
            evidence["primary_app"] = recipe["lesson"]["app"]
        # This is an incomplete evidence worksheet, not a passed publication gate.
        (staging / "evidence.pending.json").write_text(json.dumps(evidence, indent=2, ensure_ascii=False) + "\n")
        manifest = {"schema_version": 1, "kind": "actual_screen_walkthrough_assembly", "lesson_id": ident, "assembled_at": assembled,
                    "publishable": False, "publication_status": "pending_frame_review_browser_playback_and_capture_evidence_gate",
                    "browser_playback": {"status": "pending", "proof": []}, "full_decode": "passed",
                    "decoded_narration_seconds": measured, "duration_seconds": recipe["duration"], "width": WIDTH, "height": HEIGHT, "fps": FPS,
                    "actual_media": {**media_info, "decoded_audio_seconds": decoded_output_audio, "decoded_video_frames": frame_count},
                    "codec_request": {"video": "H264/libx264", "audio": "AAC", "pixel_format": "yuv420p"},
                    "source_hashes": recipe["source_hashes"], "font": {"file": str(font_path), "sha256": _hash(font_path)},
                    "outputs": {"video": file_ref(movie), "srt": file_ref(srt), "vtt": file_ref(vtt), "chapters": file_ref(chapter_file), "poster": file_ref(poster)},
                    "screenshots": {sid: {"sha256": s["metadata"]["sha256"], "layout": s["layout"], "source_intact": True} for sid, s in recipe["screenshots"].items()},
                    "timeline": entries, "rendered_segments": segments,
                    "limitations": ["Source review, literal labels and accessible icon-control names are review observations, not OCR or a claim that metadata authenticates pixels.", "DOM control rectangles refer only to the raw screenshot; extracted frames have no DOM. Icon controls require separate hash-bound frame control_review, with reviewed_control_names drawn from the validated source image.", "Extracted frame review and beginning/middle/end browser playback evidence are still required.", "No publication, site export, external delivery, native hardware exercise, or new narration was performed."]}
        (staging / "assembly.json").write_text(json.dumps(manifest, indent=2, ensure_ascii=False) + "\n")
        output.parent.mkdir(parents=True, exist_ok=True)
        need(not output.exists(), "output_dir", "appeared during rendering; previous work must not be replaced")
        shutil.copytree(staging, output)  # No overwrite, even across filesystem boundaries.
        return manifest


def main(argv=None):
    parser = argparse.ArgumentParser(description=__doc__)
    parser.add_argument("--lesson", type=Path, required=True)
    parser.add_argument("--plan", type=Path, required=True)
    parser.add_argument("--asset-root", type=Path, required=True)
    parser.add_argument("--output-dir", type=Path, required=True)
    parser.add_argument("--ffmpeg", default="ffmpeg")
    parser.add_argument("--font", type=Path)
    parser.add_argument("--check", action="store_true", help="validate inputs and decode narration only; create no video")
    args = parser.parse_args(argv)
    try:
        result = render(args.lesson, args.plan, args.asset_root, args.output_dir, args.ffmpeg, args.font, args.check)
    except (AssemblyError, OSError) as exc:
        print(json.dumps({"passed": False, "publishable": False, "error": str(exc)}, indent=2))
        return 1
    print(json.dumps({"passed": True, "publishable": False, "lesson_id": result["lesson_id"], "status": result.get("status", result.get("publication_status")), "output_dir": str(args.output_dir) if not args.check else None}, indent=2))
    return 0


if __name__ == "__main__":
    raise SystemExit(main())
