#!/usr/bin/env python3
"""Extract real encoded cue frames and QA-only reading aids; infer NO approval.

All raw screenshots, master, original25PNGframes and pending evidence remain
unchanged. Caption sheets crop only actual encoded frame footers as QA aids;
they are never operational application-capture evidence. No reviewed native
frame receipt is generated by extraction or numerical image comparison.
"""
import argparse,hashlib,json,subprocess,sys
from pathlib import Path
sys.dont_write_bytecode=True
ROOT=Path(__file__).resolve().parents[2];S=ROOT/'sources'
TAKE=S/'expansion/rendered/app-unit-inventory-native-counts-take-01'
MASTER='f5d3a2f74417a1722ade66bb191691fa6ae01739c29bf49801f3ca0beecae62d'

def sha(p):return hashlib.sha256(p.read_bytes()).hexdigest()
def main():
 p=argparse.ArgumentParser(description=__doc__);p.add_argument('--ffmpeg',required=True);args=p.parse_args()
 from PIL import Image,ImageChops,ImageDraw,ImageStat
 sys.path.insert(0,str(ROOT/'scripts'));from render_walkthrough import load_cues
 movie=TAKE/'app-unit-inventory-native-counts.mp4';assert sha(movie)==MASTER
 a=json.loads((TAKE/'assembly.json').read_text());e=json.loads((TAKE/'evidence.pending.json').read_text())
 shots={r['id']:r for r in e['screenshots']};cues=load_cues(TAKE/'app-unit-inventory-native-counts.srt')
 assert len(cues)==90 and len(e['rendered_segments'])==25
 output=TAKE/'frame-qa';assert not output.exists(),'Preserve previous extraction.';output.mkdir()
 numbers=[round((c['start']+c['end'])/2*30) for c in cues];assert len(set(numbers))==90
 select='+'.join('eq(n\\,'+str(n)+')' for n in numbers)
 subprocess.run([args.ffmpeg,'-nostdin','-v','error','-i',str(movie),'-vf','select='+select,'-fps_mode','vfr','-frames:v','90','-q:v','2',str(output/'cue-%04d.jpg')],check=True)
 rows=[]
 for number,(cue,frame_number) in enumerate(zip(cues,numbers),1):
  path=output/f'cue-{number:04}.jpg';image=Image.open(path).convert('RGB');assert image.size==(1920,1080)
  at=frame_number/30;assert cue['start']<=at<cue['end'];segment=next(s for s in a['rendered_segments'] if s['start']<=at<s['end'])
  rows.append({'cue':number,'file':path.relative_to(S).as_posix(),'sha256':sha(path),'width':1920,'height':1080,
   'actual_frame_number':frame_number,'actual_time':at,'requested_midpoint':(cue['start']+cue['end'])/2,
   'caption_text':cue['text'],'source_id':segment['screenshot_id'],'source_sha256':shots[segment['screenshot_id']]['sha256'],
   'video_sha256':MASTER,'visual_review_status':'pending_actual_caption_inspection'})
 metrics=[]
 for segment in a['rendered_segments']:
  row=shots[segment['screenshot_id']];source=Image.open(S/row['file']).convert('RGB');layout=a['screenshots'][row['id']]['layout']
  frame=Image.open(S/segment['frame']['file']).convert('RGB');assert source.size==(2732,2048) and frame.size==(1920,1080)
  assert layout['cropped'] is False and layout['measured_native_dpr']==2 and layout['output_pixels_per_logical_point']==.890625
  box=(layout['x'],layout['y'],layout['x']+layout['width'],layout['y']+layout['height'])
  delta=ImageChops.difference(source.resize((layout['width'],layout['height']),Image.Resampling.LANCZOS),frame.crop(box))
  means=ImageStat.Stat(delta).mean
  metrics.append({'frame':segment['frame']['file'],'frame_sha256':sha(S/segment['frame']['file']),
   'source_id':row['id'],'source_sha256':row['sha256'],'native_binding':segment['frame']['native_binding'],
   'fitted_region':layout,'mean_absolute_error_per_channel':means,'mean_absolute_error_255':sum(means)/3,
   'method':'Entire encoded full-viewportUI region compared with unchanged rawPNG resizedLANCZOS. Normal H264 color/compression differences; numerical comparison is not OCR, semantic review or pixel authentication.'})
 sheets=[]
 for first in range(0,90,6):
  group=rows[first:first+6];sheet=Image.new('RGB',(1920,160*len(group)),(30,38,50));draw=ImageDraw.Draw(sheet)
  for offset,row in enumerate(group):
   draw.text((16,offset*160+8),f"Cue{row['cue']:03} | actual encoded frame{row['actual_frame_number']} at{row['actual_time']:.6f}s",fill='white')
   frame=Image.open(S/row['file']).convert('RGB');sheet.paste(frame.crop((0,960,1920,1080)),(0,offset*160+40))
  path=output/f'caption-sheet-{first//6+1:02}.png';sheet.save(path)
  sheets.append({'file':path.relative_to(S).as_posix(),'sha256':sha(path),'cues':[r['cue'] for r in group],
   'kind':'QA_only_actual_encoded_caption_footer_strips_not_application_evidence'})
 report={'kind':'native_count_actual_encoded_QA_inputs_not_review','video_sha256':MASTER,'actual_interval_frames':25,
  'actual_cue_frames':90,'cue_frames':rows,'full_UI_pixel_comparisons':metrics,'caption_reading_sheets':sheets,
  'visual_approval_inferred':False,'native_frame_review_generated':False,'browser_playback_inferred':False,'publication_approved':False}
 path=output/'extraction-and-pixel-metrics.json';path.write_text(json.dumps(report,indent=2,ensure_ascii=False)+'\n')
 assert sha(movie)==MASTER
 print(json.dumps({'extraction_passed':True,'intervals':25,'cues':90,'caption_sheets':15,'visual_review':'pending',
  'metrics_sha256':sha(path),'max_full_UI_MAE_255':max(r['mean_absolute_error_255'] for r in metrics)}))
if __name__=='__main__':main()
