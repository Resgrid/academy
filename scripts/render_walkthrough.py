#!/usr/bin/env python3
"""Assemble a staged 1080p walkthrough from approved speech and real screenshots.

See sources/expansion/PRODUCTION.md for the explicit plan schema. No cue timing,
screen/control correspondence, speech, capture review, or playback evidence is
inferred. Validation uses the stdlib; rendering additionally needs Pillow and
FFmpeg. Existing source/media files are never overwritten. A completed render
is still publishable=false, with frame review and browser playback pending.
Icon-only controls use verify_capture_evidence.visible_controls and its separate
hash-bound capture_review. Accessible names never become literal visible_labels.
The existing plan.screenshot_reviews approval is additionally required. Extracted
frames need their own control_review after actual rendering; DOM rectangles are
not copied into frames and no passed review is generated by this assembler.

Optional plan.instruction_mapping="reviewed_scene_coverage" separates authored
scene label coverage from verbatim speech. All authored labels must be captured;
each cue's exact control names still map to its pictured UI. Natural wording
requires explicit spoken_references plus a scene.instruction_review bound using
instruction_scene_digest to the fully expanded original SRT cues, screen times
and real capture records. No review is inferred. Legacy plans remain strict.
plan.display_context can add a short accurate label outside the intact image.
"""

